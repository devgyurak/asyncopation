"""Asyncopation: truly asynchronous execution for the Django ORM.

SQL is still generated by Django's compiler (synchronous, CPU-only); only evaluation is
re-implemented on top of native async drivers (psycopg3, asyncmy). See docs/architecture.md.

``setup`` / ``close`` / ``configure`` import ``asyncopation.connection`` when called, and ``observe``
/ ``intercept`` (ADR-0005) and the query facade load on first access, so that ``import asyncopation`` (which Django
does before the app registry is ready) imports neither Django nor a database driver.
"""

from __future__ import annotations

from collections.abc import Iterable
from typing import TYPE_CHECKING, Any

from asyncopation.errors import ConcurrentQueryError, SyncEvaluationError

if TYPE_CHECKING:
    from asyncopation.connection.hooks import intercept, observe
    from asyncopation.query import AsyncObjects, AsyncQuerySet, aq

__version__ = "0.0.0"
__all__ = [
    "AsyncObjects",
    "AsyncQuerySet",
    "ConcurrentQueryError",
    "SyncEvaluationError",
    "aq",
    "close",
    "configure",
    "intercept",
    "observe",
    "setup",
]


if not TYPE_CHECKING:  # a module-level __getattr__ would make every missing name type-check

    def __getattr__(name: str) -> Any:
        """Load the Django-facing facade only when it is used (PEP 562)."""
        if name in ("aq", "AsyncObjects", "AsyncQuerySet"):
            from asyncopation import query

            return getattr(query, name)
        if name in ("observe", "intercept"):
            from asyncopation.connection import hooks

            return getattr(hooks, name)
        raise AttributeError(f"module 'asyncopation' has no attribute {name!r}")


def configure() -> None:
    """Build the per-alias configuration from ``DATABASES`` (``AppConfig.ready()`` does it)."""
    from asyncopation.connection import lifecycle

    lifecycle.configure()


async def setup(aliases: Iterable[str] | None = None) -> None:
    """Open the drivers in the running loop (default: every alias with a supported engine)."""
    from asyncopation.connection import lifecycle

    await lifecycle.setup(aliases)


async def close(timeout: float | None = None) -> None:  # noqa: ASYNC109 - public API, see lifecycle.close
    """Close the running loop's drivers; ``timeout=None`` is ``lifecycle.DEFAULT_CLOSE_TIMEOUT``."""
    from asyncopation.connection import lifecycle

    await lifecycle.close(lifecycle.DEFAULT_CLOSE_TIMEOUT if timeout is None else timeout)
